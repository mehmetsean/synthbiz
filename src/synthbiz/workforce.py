"""Workforce tables."""

import json
import random
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Any

from . import __version__
from .io import NOTICE, _foreign_manifest, _prepare, _sha256, _write_csv
from .names import person_names
from .schema import DISCLAIMER

MAX_STAFF = 500
MAX_DAYS = 366

TABLES: dict[str, list[str]] = {
    "staff": [
        "staff_id",
        "display_name",
        "skills",
        "min_minutes_week",
        "max_minutes_week",
        "cost_cents_hour",
        "max_consecutive_days",
    ],
    "shifts": ["shift_id", "start", "end", "crosses_midnight"],
    "demand": ["date", "shift_id", "skill", "required"],
    "availability": ["staff_id", "date", "shift_id", "kind"],
}

SHIFTS = [("DAY", 360, 840), ("EVE", 840, 1320), ("NIGHT", 1320, 360)]
SKILL_CYCLE = ["RN", "RN", "MA", "RN", "MA", "FRONT", "RN", "MA", "FRONT", "RN"]
WAGE_CENTS = {"RN": (4200, 5200), "MA": (2200, 2800), "FRONT": (1900, 2400)}
SECOND_SKILL_RATE = 0.3
CONTRACTS = [(1920, 2400), (960, 1440), (0, 960)]
# shift share
WEEKDAY_SHARE = {"DAY": 0.25, "EVE": 0.2, "NIGHT": 0.1}
WEEKEND_FACTOR = 0.6
NO_NIGHT = {"FRONT"}
OFF_RATE = 0.04
PREFER_OFF_RATE = 0.08
PREFER_ON_RATE = 0.06


DESCRIPTIONS = {
    "staff": (
        "One row per person. The `skills` column is a list joined by |. "
        "Minutes are per week."
    ),
    "shifts": (
        "Shift times in minutes after midnight. "
        "The `crosses_midnight` column is 1 if the shift ends the next day."
    ),
    "demand": "People needed per date, shift and skill. Weekends need fewer people.",
    "availability": (
        "Per person and date. The shift_id column is a shift or * for the whole day. "
        "The kind column is unavailable, prefer_off or prefer_on."
    ),
}
README = """\
Workforce tables (synthetic data)

This folder is synthetic data made by synthbiz {version}. Every name, wage and
date was generated by code. The display names in staff.csv are joined from
invented first and last name lists. Any match with a real person is unintended.

{disclaimer}

Copyright (c) 2026 Mehmet Tuzunkan.
{notice}

Files:
- Tables: staff.csv, shifts.csv, demand.csv and availability.csv.
  See data_dictionary.md.
- The manifest.json file holds the seed, parameters, row counts and a sha256 of
  every file.
"""


@dataclass(frozen=True)
class WorkforceParams:
    seed: int = 42
    staff: int = 20
    days: int = 28
    start_date: date = date(2025, 6, 2)


@dataclass
class WorkforceDataset:
    params: WorkforceParams
    tables: dict[str, list[dict[str, Any]]]


def _staff(rng: random.Random, count: int) -> list[dict[str, Any]]:
    rows = []
    for i, name in enumerate(person_names(rng, count)):
        skills = [SKILL_CYCLE[i % len(SKILL_CYCLE)]]
        if rng.random() < SECOND_SKILL_RATE:
            other = rng.choice(sorted(set(WAGE_CENTS) - set(skills)))
            skills.append(other)
        low, high = rng.choice(CONTRACTS)
        wage_low, wage_high = WAGE_CENTS[skills[0]]
        rows.append(
            {
                "staff_id": f"S-{i + 1:04d}",
                "display_name": name,
                "skills": "|".join(skills),
                "min_minutes_week": low,
                "max_minutes_week": high,
                "cost_cents_hour": rng.randrange(wage_low, wage_high + 1, 25),
                "max_consecutive_days": rng.randint(4, 6),
            }
        )
    return rows


def _shifts() -> list[dict[str, Any]]:
    return [
        {
            "shift_id": sid,
            "start": start,
            "end": end,
            "crosses_midnight": 1 if end < start else 0,
        }
        for sid, start, end in SHIFTS
    ]


def _demand(staff: list[dict[str, Any]], days: list[date]) -> list[dict[str, Any]]:
    heads: dict[str, int] = {}
    for r in staff:
        for s in r["skills"].split("|"):
            heads[s] = heads.get(s, 0) + 1
    rows = []
    for d in days:
        weekend = d.weekday() >= 5
        for sid, _, _ in SHIFTS:
            for skill in sorted(heads):
                if sid == "NIGHT" and skill in NO_NIGHT:
                    continue
                need = max(1, round(heads[skill] * WEEKDAY_SHARE[sid]))
                if weekend:
                    need = max(1, round(need * WEEKEND_FACTOR))
                rows.append(
                    {
                        "date": d.isoformat(),
                        "shift_id": sid,
                        "skill": skill,
                        "required": need,
                    }
                )
    return rows


def _availability(
    rng: random.Random, staff: list[dict[str, Any]], days: list[date]
) -> list[dict[str, Any]]:
    rows = []
    ids = [sid for sid, _, _ in SHIFTS]
    for r in staff:
        for d in days:
            x = rng.random()
            if x < OFF_RATE:
                kind, shift = "unavailable", "*"
            elif x < OFF_RATE + PREFER_OFF_RATE:
                kind, shift = "prefer_off", rng.choice(["*"] + ids)
            elif x < OFF_RATE + PREFER_OFF_RATE + PREFER_ON_RATE:
                kind, shift = "prefer_on", rng.choice(ids)
            else:
                continue
            rows.append(
                {
                    "staff_id": r["staff_id"],
                    "date": d.isoformat(),
                    "shift_id": shift,
                    "kind": kind,
                }
            )
    return rows


def generate_workforce(params: WorkforceParams) -> WorkforceDataset:
    if not 1 <= params.staff <= MAX_STAFF:
        raise ValueError(f"staff must be between 1 and {MAX_STAFF}")
    if not 1 <= params.days <= MAX_DAYS:
        raise ValueError(f"days must be between 1 and {MAX_DAYS}")
    rng = random.Random(params.seed)
    if params.start_date > date.max - timedelta(days=params.days - 1):
        raise ValueError(
            f"start_date plus days must stay on or before {date.max.isoformat()}"
        )
    days = [params.start_date + timedelta(days=i) for i in range(params.days)]
    staff = _staff(rng, params.staff)
    tables = {
        "staff": staff,
        "shifts": _shifts(),
        "demand": _demand(staff, days),
        "availability": _availability(rng, staff, days),
    }
    return WorkforceDataset(params, tables)


def known_files() -> list[str]:
    return [f"{t}.csv" for t in TABLES] + [
        "data_dictionary.md",
        "README.txt",
        "manifest.json",
    ]


def _dictionary() -> str:
    lines = ["# Data dictionary", "", DISCLAIMER, "", "Money is in integer cents."]
    lines += ["Times are integer minutes.", ""]
    for name, cols in TABLES.items():
        lines += [f"## {name}", "", DESCRIPTIONS[name], ""]
        lines += [f"Columns: {', '.join(cols)}", ""]
    return "\n".join(lines)


def write_workforce(ds: WorkforceDataset, out: Path, force: bool = False) -> None:
    if force and _foreign_manifest(out, "workforce"):
        raise FileExistsError(
            f"{out} holds a manifest.json that is not a workforce manifest, "
            "use an empty folder"
        )
    _prepare(out, force, known_files())
    for name, cols in TABLES.items():
        _write_csv(out / f"{name}.csv", cols, ds.tables[name])
    (out / "data_dictionary.md").write_text(_dictionary(), "utf-8")
    text = README.format(version=__version__, disclaimer=DISCLAIMER, notice=NOTICE)
    (out / "README.txt").write_text(text, "utf-8")
    written = [f"{t}.csv" for t in TABLES] + ["data_dictionary.md", "README.txt"]
    p = ds.params
    manifest = {
        "synthetic": True,
        "synthbiz_version": __version__,
        "kind": "workforce",
        "parameters": {
            "seed": p.seed,
            "staff": p.staff,
            "days": p.days,
            "start_date": p.start_date.isoformat(),
        },
        "row_counts": {t: len(ds.tables[t]) for t in TABLES},
        "files": {n: _sha256(out / n) for n in sorted(written)},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", "utf-8")
