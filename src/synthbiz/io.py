"""Write and read a dataset folder."""

import csv
import hashlib
import json
from datetime import date
from pathlib import Path
from typing import Any

from . import __version__
from .generate import Dataset
from .schema import (
    DISCLAIMER,
    LABEL_COLUMNS,
    TABLE_NAMES,
    columns,
    data_dictionary,
    schema_dict,
)

FORMATS = ("csv", "parquet")

README = """\
{company} (fictional)

This folder is synthetic data made by synthbiz {version}. Every name, amount and
date was generated by code.

{disclaimer}

License: CC BY 4.0, https://creativecommons.org/licenses/by/4.0/

Files:
- one file per table, see data_dictionary.md and schema.json
- labels.csv lists every planted anomaly (table, row_id, anomaly_type, details)
- manifest.json holds the seed, parameters and a sha256 of every file

Check it with: synthbiz check <this folder>
"""


def _write_csv(path: Path, header: list[str], rows: list[dict[str, Any]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([r[c] for c in header])


def _write_parquet(path: Path, name: str, rows: list[dict[str, Any]]) -> None:
    import pyarrow as pa
    import pyarrow.parquet as pq

    kinds = {c["name"]: c["type"] for c in schema_dict()["tables"][name]["columns"]}
    types = {"string": pa.string(), "integer": pa.int64(), "date": pa.date32()}
    fields = [pa.field(c, types[kinds[c]]) for c in columns(name)]
    data: dict[str, list[Any]] = {}
    for c in columns(name):
        vals = [r[c] for r in rows]
        if kinds[c] == "date":
            vals = [date.fromisoformat(v) for v in vals]
        data[c] = vals
    pq.write_table(pa.table(data, schema=pa.schema(fields)), path)


def known_files() -> list[str]:
    """Every file name synthbiz may write into a dataset folder."""
    names = [f"{t}.{ext}" for t in TABLE_NAMES for ext in ("csv", "parquet")]
    return names + [
        "labels.csv",
        "schema.json",
        "data_dictionary.md",
        "README.txt",
        "manifest.json",
    ]


def _prepare(out: Path, force: bool) -> None:
    if out.exists() and not out.is_dir():
        raise FileExistsError(f"{out} is a file, not a folder")
    out.mkdir(parents=True, exist_ok=True)
    if not any(out.iterdir()):
        return
    if not force:
        raise FileExistsError(
            f"{out} is not empty, use --force to replace the synthbiz files in it"
        )
    for name in known_files():
        f = out / name
        if f.is_file() or f.is_symlink():
            f.unlink()


def write_dataset(
    ds: Dataset, out: Path, fmt: str = "csv", force: bool = False
) -> None:
    if fmt not in FORMATS:
        raise ValueError(f"format must be one of {FORMATS}")
    _prepare(out, force)
    written: list[str] = []
    for name in TABLE_NAMES:
        if fmt == "csv":
            _write_csv(out / f"{name}.csv", columns(name), ds.tables[name])
        else:
            _write_parquet(out / f"{name}.parquet", name, ds.tables[name])
        written.append(f"{name}.{fmt}")
    _write_csv(out / "labels.csv", LABEL_COLUMNS, ds.labels)
    schema = schema_dict()
    (out / "schema.json").write_text(json.dumps(schema, indent=2) + "\n", "utf-8")
    (out / "data_dictionary.md").write_text(data_dictionary(schema), "utf-8")
    (out / "README.txt").write_text(
        README.format(company=ds.company, version=__version__, disclaimer=DISCLAIMER),
        "utf-8",
    )
    written += ["labels.csv", "schema.json", "data_dictionary.md", "README.txt"]
    p = ds.params
    files = {name: _sha256(out / name) for name in sorted(written)}
    manifest = {
        "synthetic": True,
        "synthbiz_version": __version__,
        "company": ds.company,
        "parameters": {
            "seed": p.seed,
            "months": p.months,
            "size": p.size,
            "anomaly_rate": p.anomaly_rate,
            "start_date": p.start_date.isoformat(),
            "format": fmt,
        },
        "anomaly_count": ds.anomaly_count,
        "files": files,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", "utf-8")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(folder: Path) -> list[str] | None:
    """Compare manifest.json hashes with the files. None if there is no manifest."""
    path = folder / "manifest.json"
    if not path.is_file():
        return None
    try:
        files = json.loads(path.read_text("utf-8"))["files"]
    except (ValueError, KeyError, TypeError, RecursionError, OSError):
        files = None
    if not isinstance(files, dict):
        return ["manifest.json could not be read"]
    allowed = set(known_files())
    errors: list[str] = []
    for name, digest in sorted(files.items()):
        f = folder / name
        if name not in allowed:
            errors.append(f"unexpected file name in manifest.json: {name!r}")
        elif not f.is_file():
            errors.append(f"{name}: listed in manifest.json but missing")
        elif _sha256(f) != digest:
            errors.append(f"{name}: sha256 differs from manifest.json")
    for name in known_files():
        if name != "manifest.json" and name not in files and (folder / name).exists():
            errors.append(f"{name}: in the folder but not in manifest.json")
    return errors


def _bad_columns(name: str, expected: list[str], found: str) -> ValueError:
    return ValueError(
        f"{name}: columns do not match the schema, "
        f"expected {','.join(expected)}, found {found[:200]}"
    )


def _check_value(name: str, where: str, column: str, kind: str, value: str) -> None:
    try:
        if kind == "integer":
            int(value)
        elif kind == "date":
            date.fromisoformat(value)
    except ValueError:
        raise ValueError(f"{name}: {where}: {column} is not a valid {kind}") from None


def _read_csv(
    path: Path, expected: list[str], types: dict[str, str] | None = None
) -> list[dict[str, Any]]:
    name = path.name
    records: list[tuple[int, list[str]]] = []
    try:
        with path.open(newline="", encoding="utf-8-sig") as f:
            reader = csv.reader(f, strict=True)
            for row in reader:
                records.append((reader.line_num, row))
    except UnicodeDecodeError:
        raise ValueError(f"{name}: not valid UTF-8") from None
    except csv.Error as e:
        raise ValueError(f"{name}: not valid CSV, {e}") from None
    except OSError as e:
        raise ValueError(f"{name}: could not read the file ({e.strerror})") from None
    while records and not records[-1][1]:
        records.pop()
    if not records:
        raise ValueError(f"{name}: file is empty")
    header = records[0][1]
    if header != expected:
        raise _bad_columns(name, expected, repr(",".join(header)))
    out: list[dict[str, Any]] = []
    for number, row in records[1:]:
        if not row:
            raise ValueError(f"{name}: line {number} is blank")
        if len(row) != len(expected):
            raise ValueError(
                f"{name}: line {number} has {len(row)} fields, expected {len(expected)}"
            )
        for column, value in zip(header, row, strict=True):
            kind = (types or {}).get(column, "string")
            _check_value(name, f"line {number}", column, kind, value)
        out.append(dict(zip(header, row, strict=True)))
    return out


def _read_parquet(
    path: Path, expected: list[str], types: dict[str, str]
) -> list[dict[str, Any]]:
    try:
        import pyarrow.parquet as pq
    except ImportError:
        raise ValueError(
            f"{path.name}: pyarrow is needed to read Parquet files, "
            "install synthbiz[parquet]"
        ) from None
    try:
        table = pq.read_table(path)
    except Exception:
        raise ValueError(f"{path.name}: not a readable Parquet file") from None
    if table.column_names != expected:
        raise _bad_columns(path.name, expected, repr(",".join(table.column_names)))
    out: list[dict[str, Any]] = []
    for number, r in enumerate(table.to_pylist(), start=1):
        row: dict[str, Any] = {}
        for k, v in r.items():
            text = "" if v is None else v.isoformat() if isinstance(v, date) else str(v)
            _check_value(path.name, f"row {number}", k, types.get(k, "string"), text)
            row[k] = text
        out.append(row)
    return out


def _types(table: str) -> dict[str, str]:
    cols = schema_dict()["tables"][table]["columns"]
    return {c["name"]: c["type"] for c in cols}


def read_dataset(
    folder: Path,
) -> tuple[dict[str, list[dict[str, Any]]], list[dict[str, Any]]]:
    """Read every table as strings, from CSV or Parquet files."""
    if not folder.is_dir():
        raise FileNotFoundError(f"folder not found: {folder}")
    tables: dict[str, list[dict[str, Any]]] = {}
    for name in TABLE_NAMES:
        csv_path = folder / f"{name}.csv"
        pq_path = folder / f"{name}.parquet"
        if csv_path.exists() and pq_path.exists():
            raise ValueError(f"both {name}.csv and {name}.parquet are in {folder}")
        if csv_path.exists():
            tables[name] = _read_csv(csv_path, columns(name), _types(name))
        elif pq_path.exists():
            tables[name] = _read_parquet(pq_path, columns(name), _types(name))
        else:
            raise FileNotFoundError(f"missing table file for {name} in {folder}")
    labels_path = folder / "labels.csv"
    labels = _read_csv(labels_path, LABEL_COLUMNS) if labels_path.exists() else []
    return tables, labels
