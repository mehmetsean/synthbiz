"""Write and read a dataset folder."""

import csv
import hashlib
import json
from datetime import date
from pathlib import Path
from typing import Any

from . import __version__
from .generate import Dataset
from .schema import (
    LABEL_COLUMNS,
    TABLE_NAMES,
    columns,
    data_dictionary,
    schema_dict,
)

FORMATS = ("csv", "parquet")

README = """\
{company} (fictional)

This folder is synthetic data made by synthbiz {version}. Every name, amount and
date was generated by code. Any match with a real business or person is
unintended.

It is for testing and learning only. Decision support only, not legal, tax,
accounting or assurance advice. No guarantee of compliance.

License: CC BY 4.0, https://creativecommons.org/licenses/by/4.0/

Files:
- one file per table, see data_dictionary.md and schema.json
- labels.csv lists every planted anomaly (table, row_id, anomaly_type, details)
- manifest.json holds the seed, parameters and a sha256 of every file

Check it with: synthbiz check <this folder>
"""


def _write_csv(path: Path, header: list[str], rows: list[dict[str, Any]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([r[c] for c in header])


def _write_parquet(path: Path, name: str, rows: list[dict[str, Any]]) -> None:
    import pyarrow as pa
    import pyarrow.parquet as pq

    kinds = {c["name"]: c["type"] for c in schema_dict()["tables"][name]["columns"]}
    types = {"string": pa.string(), "integer": pa.int64(), "date": pa.date32()}
    fields = [pa.field(c, types[kinds[c]]) for c in columns(name)]
    data: dict[str, list[Any]] = {}
    for c in columns(name):
        vals = [r[c] for r in rows]
        if kinds[c] == "date":
            vals = [date.fromisoformat(v) for v in vals]
        data[c] = vals
    pq.write_table(pa.table(data, schema=pa.schema(fields)), path)


def known_files() -> list[str]:
    """Every file name synthbiz may write into a dataset folder."""
    names = [f"{t}.{ext}" for t in TABLE_NAMES for ext in ("csv", "parquet")]
    return names + [
        "labels.csv",
        "schema.json",
        "data_dictionary.md",
        "README.txt",
        "manifest.json",
    ]


def _prepare(out: Path, force: bool) -> None:
    if out.exists() and not out.is_dir():
        raise FileExistsError(f"{out} is a file, not a folder")
    out.mkdir(parents=True, exist_ok=True)
    if not any(out.iterdir()):
        return
    if not force:
        raise FileExistsError(
            f"{out} is not empty, use --force to replace the synthbiz files in it"
        )
    for name in known_files():
        f = out / name
        if f.is_file() or f.is_symlink():
            f.unlink()


def write_dataset(
    ds: Dataset, out: Path, fmt: str = "csv", force: bool = False
) -> None:
    if fmt not in FORMATS:
        raise ValueError(f"format must be one of {FORMATS}")
    _prepare(out, force)
    written: list[str] = []
    for name in TABLE_NAMES:
        if fmt == "csv":
            _write_csv(out / f"{name}.csv", columns(name), ds.tables[name])
        else:
            _write_parquet(out / f"{name}.parquet", name, ds.tables[name])
        written.append(f"{name}.{fmt}")
    _write_csv(out / "labels.csv", LABEL_COLUMNS, ds.labels)
    schema = schema_dict()
    (out / "schema.json").write_text(json.dumps(schema, indent=2) + "\n", "utf-8")
    (out / "data_dictionary.md").write_text(data_dictionary(schema), "utf-8")
    (out / "README.txt").write_text(
        README.format(company=ds.company, version=__version__), "utf-8"
    )
    written += ["labels.csv", "schema.json", "data_dictionary.md", "README.txt"]
    p = ds.params
    files = {name: _sha256(out / name) for name in sorted(written)}
    manifest = {
        "synthetic": True,
        "synthbiz_version": __version__,
        "company": ds.company,
        "parameters": {
            "seed": p.seed,
            "months": p.months,
            "size": p.size,
            "anomaly_rate": p.anomaly_rate,
            "start_date": p.start_date.isoformat(),
            "format": fmt,
        },
        "anomaly_count": ds.anomaly_count,
        "files": files,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", "utf-8")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(folder: Path) -> list[str] | None:
    """Compare manifest.json hashes with the files. None if there is no manifest."""
    path = folder / "manifest.json"
    if not path.is_file():
        return None
    try:
        files = json.loads(path.read_text("utf-8"))["files"]
    except (ValueError, KeyError, TypeError):
        files = None
    if not isinstance(files, dict):
        return ["manifest.json could not be read"]
    errors: list[str] = []
    for name, digest in sorted(files.items()):
        f = folder / name
        if not f.is_file():
            errors.append(f"{name}: listed in manifest.json but missing")
        elif _sha256(f) != digest:
            errors.append(f"{name}: sha256 differs from manifest.json")
    for name in known_files():
        if name != "manifest.json" and name not in files and (folder / name).exists():
            errors.append(f"{name}: in the folder but not in manifest.json")
    return errors


def _read_csv(path: Path) -> list[dict[str, Any]]:
    with path.open(newline="", encoding="utf-8") as f:
        return [dict(r) for r in csv.DictReader(f)]


def _read_parquet(path: Path) -> list[dict[str, Any]]:
    import pyarrow.parquet as pq

    rows = pq.read_table(path).to_pylist()
    return [
        {
            k: "" if v is None else v.isoformat() if isinstance(v, date) else str(v)
            for k, v in r.items()
        }
        for r in rows
    ]


def read_dataset(
    folder: Path,
) -> tuple[dict[str, list[dict[str, Any]]], list[dict[str, Any]]]:
    """Read every table as strings, from CSV or Parquet files."""
    if not folder.is_dir():
        raise FileNotFoundError(f"folder not found: {folder}")
    tables: dict[str, list[dict[str, Any]]] = {}
    for name in TABLE_NAMES:
        csv_path = folder / f"{name}.csv"
        pq_path = folder / f"{name}.parquet"
        if csv_path.exists() and pq_path.exists():
            raise ValueError(f"both {name}.csv and {name}.parquet are in {folder}")
        if csv_path.exists():
            tables[name] = _read_csv(csv_path)
        elif pq_path.exists():
            tables[name] = _read_parquet(pq_path)
        else:
            raise FileNotFoundError(f"missing table file for {name} in {folder}")
    labels = (
        _read_csv(folder / "labels.csv") if (folder / "labels.csv").exists() else []
    )
    return tables, labels
