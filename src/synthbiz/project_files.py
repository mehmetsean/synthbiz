"""Project folder writer."""

import json
from pathlib import Path

from . import __version__
from .io import NOTICE, _foreign_manifest, _prepare, _sha256, _write_csv
from .mspdi import COPYRIGHT, project_xml
from .project import RANGE_COLUMNS, RISK_COLUMNS, ProjectDataset
from .schema import DISCLAIMER

UNITS = {
    "ranges": "percent of plan duration",
    "risk_minutes": "working minutes",
    "risk_cents": "cents",
}

README = """\
Project schedule (synthetic data)

This folder is synthetic data made by synthbiz {version}. Every task name, date
and cost was generated by code.

{disclaimer}

Copyright (c) 2026 Mehmet Tuzunkan.
{notice}

Files:
- project.xml: the plan in Microsoft Project XML (MSPDI) form.
- ranges.csv: min, most_likely and max are percent of plan duration.
- risks.csv: risk events, with impacts in working minutes and in cents.
- data_dictionary.md: every column and unit.
- manifest.json: the seed, parameters, counts, units and a sha256 of every
  file listed above.
"""

DICTIONARY = f"""\
# Data dictionary

{DISCLAIMER}

{COPYRIGHT}

## project.xml

One calendar, Monday to Friday, 08:00 to 12:00 and 13:00 to 17:00, with US
federal holidays as exceptions (Juneteenth from 2021). Durations are working
time. LinkLag is in tenths of a minute. Link Type is 0 for FF, 1 for FS, 2 for
SF and 3 for SS. FixedCost and Cost are in hundredths of the currency unit
(cents). Microsoft does not state the unit on the pages named in
docs/adr/0019-project-schedules.md of synthbiz. A work task's Cost is FixedCost
plus a day rate times its duration in days. The file holds no resources or
assignments, so a tool that recomputes cost may get other totals. A lead
(negative lag) is never longer than the predecessor's duration, and a link from
a milestone has no lead. Summary tasks have no Duration. No task has a Start or
Finish date. The file has not been opened in Microsoft Project.

## ranges.csv

One row per task that is not a summary task or a milestone. The columns `min`,
`most_likely` and `max` are percent of plan duration, so 100 is the duration in
project.xml.

- `uid`: task UID in project.xml.
- `dist`: triangular, pert or uniform. For uniform, min and max are the bounds.
  most_likely is written but not used.
- `min`, `most_likely`, `max`: whole percent.
- `corr_group`: tasks with the same group name are meant to move together. A
  group name is on at least two rows. Empty means no group.

## risks.csv

One row per risk event.

- `risk_id`: id of the risk.
- `probability`: chance that the event happens, between 0 and 1.
- `impact_dist`: triangular, pert or uniform, for both impacts. For uniform, the
  min and max columns are the bounds. The most_likely columns are written but
  not used.
- `min_minutes`, `most_likely_minutes`, `max_minutes`: delay in working minutes
  added to every affected task.
- `min_cents`, `most_likely_cents`, `max_cents`: cost of the event in cents.
- `affected_uids`: task UIDs joined by |.
- `corr_group`: risks with the same group name are meant to move together. A
  group name is on at least two rows. Empty means no group.
"""

DATA_FILES = [
    "project.xml",
    "ranges.csv",
    "risks.csv",
    "data_dictionary.md",
    "README.txt",
]


def known_files() -> list[str]:
    return DATA_FILES + ["manifest.json"]


def write_project(ds: ProjectDataset, out: Path, force: bool = False) -> None:
    if force and _foreign_manifest(out, "project"):
        raise FileExistsError(
            f"{out} holds a manifest.json that is not a project manifest, "
            "use an empty folder"
        )
    _prepare(out, force, known_files())
    (out / "project.xml").write_bytes(project_xml(ds))
    _write_csv(out / "ranges.csv", RANGE_COLUMNS, ds.ranges)
    _write_csv(out / "risks.csv", RISK_COLUMNS, ds.risks)
    (out / "data_dictionary.md").write_text(DICTIONARY, "utf-8", newline="\n")
    text = README.format(version=__version__, disclaimer=DISCLAIMER, notice=NOTICE)
    (out / "README.txt").write_text(text, "utf-8", newline="\n")
    p = ds.params
    manifest = {
        "synthetic": True,
        "synthbiz_version": __version__,
        "kind": "project",
        "parameters": {
            "seed": p.seed,
            "tasks": p.tasks,
            "start_date": p.start_date.isoformat(),
        },
        "project_start": ds.start.isoformat(),
        "holidays_listed_through_year": ds.holiday_end_year,
        "counts": {
            "tasks": len(ds.tasks),
            "summary_tasks": sum(t.summary for t in ds.tasks),
            "milestones": sum(t.milestone for t in ds.tasks),
            "links": len(ds.links),
            "holidays": len(ds.holidays),
            "ranges": len(ds.ranges),
            "risks": len(ds.risks),
        },
        "units": UNITS,
        "files": {n: _sha256(out / n) for n in sorted(DATA_FILES)},
    }
    (out / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", "utf-8", newline="\n"
    )
